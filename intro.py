def pick(seq, key, salt):
    h = int(hashlib.md5(f"{key}:{salt}".encode()).hexdigest(), 16)
    return seq[h % len(seq)]

def topic_of(p):
    text = f"{p.get('title','')} {p.get('summary','')} {p.get('target','')}"
    for kws, name, lines in TOPICS:
        if any(k in text for k in kws):
            return name, lines
    return "생활지원", DEFAULT_EMPATHY

def intro_html(p):
    nick = html.escape(CFG.get("blog_nickname", "지원금 알리미"))
    _, lines = topic_of(p)
    k, t = p["id"], html.escape(p["title"])
    g = pick(GREETINGS, k, "g").format(nick=nick)
    first = (g + " " if g else "") + pick(LEADS, k, "l").format(t=f"<strong>{t}</strong>")
    second = pick(lines, k, "e") + (" " + pick(PROMISES, k, "p") if pick(PROMISES, k, "p") else "")
    return f"<p>{first}</p>\n<p>{second}</p>\n"

def closing_html(p):
    return f"<p>{pick(CLOSINGS, p['id'], 'c')}</p>\n"
